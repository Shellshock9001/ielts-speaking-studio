const assert=require('node:assert/strict');
const {chromium}=require('../node_modules/playwright-core');
const base=process.env.SPEAKLAB_BASE||'http://127.0.0.1:5174/ielts-speaking-studio/';
const exe=process.env.BROWSER_EXECUTABLE||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const passed=[];
function log(name){passed.push(name);console.log('PASS',name)}
async function stored(page){return page.evaluate(()=>JSON.parse(localStorage.getItem('speaklab-progress-v1')))}
const sleep=ms=>new Promise(resolve=>setTimeout(resolve,ms));
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:exe,
  args:['--no-sandbox','--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 try{
  const context=await browser.newContext({viewport:{width:940,height:780},deviceScaleFactor:1,reducedMotion:'reduce'});
  await context.addInitScript(()=>{
   const old=HTMLCanvasElement.prototype.getContext;
   HTMLCanvasElement.prototype.getContext=function(kind,...args){
    if(['webgl','webgl2','experimental-webgl'].includes(kind))return null;
    return old.call(this,kind,...args);
   };
  });
  const page=await context.newPage();
  await page.clock.install();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.locator('.ww-2d-world').waitFor({timeout:25000});
  const node=name=>page.locator('.ww-2d-field button').filter({hasText:name}).first();
  const equip=async(name)=>page.getByRole('button',{name:'Equip '+name,exact:false}).click();
  await node('Sunberry shrub').click();
  assert.equal((await stored(page)).field.inventory.berries,2);
  await sleep(300);
  await node('Sunberry shrub').click();
  assert.equal((await stored(page)).field.inventory.berries,2);
  log('fruit can be collected and cannot be duplicated today');
  await equip('Spade');
  await sleep(300);
  await node('Buried curiosity').click();
  assert.equal((await stored(page)).field.inventory.clay,1);
  log('spade unearths a persistent clay discovery');
  await sleep(300);
  await node('Flower garden').click();
  assert.equal((await stored(page)).field.inventory.seeds,5);
  assert((await stored(page)).field.gardens['0:garden']);
  log('spade plants a real flower garden using seed inventory');
  await equip('Watering Can');
  await sleep(300);
  await node('Flower garden').click();
  assert((await stored(page)).field.gardens['0:garden'].wateredAt!==null);
  log('watering changes persistent garden state');
  await page.clock.fastForward(32000);
  await equip('Gather');
  await sleep(300);
  await node('Flower garden').click();
  assert.equal((await stored(page)).field.inventory.petals,2);
  log('fully grown garden yields flowers and another seed');
  await equip('Butterfly Net');
  let bugs=0;
  for(let i=0;i<8;i++){
   await sleep(250);
   await node('Fluttering butterfly').click();
   bugs=(await stored(page)).field.inventory.bugs;
   if(bugs)break;
   await page.clock.fastForward(500);
  }
  assert.equal(bugs,1,'Butterfly should eventually be caught with timed net swing');
  log('moving insect catching has a timing challenge and a real reward');
  await page.getByRole('button',{name:'Open my satchel'}).click();
  await page.getByRole('heading',{name:'My Explorer Satchel'}).waitFor();
  const before=await stored(page);
  assert(before.field.inventory.berries>=1&&before.field.inventory.petals>=2);
  await page.getByRole('button',{name:'Craft bouquet'}).click();
  assert.equal((await stored(page)).field.inventory.gifts,1);
  log('crafting consumes actual materials and yields a gift');
  await page.getByRole('button',{name:'Close activity and return to world'}).click();
  await page.locator('.ww-2d-map').getByRole('button',{name:'Friendship Orchard'}).click();
  await page.getByRole('button',{name:'Give bouquet to Pip'}).click();
  const afterGift=await stored(page);
  assert.equal(afterGift.field.inventory.gifts,0);
  assert.equal(afterGift.field.friends['student:8.1'],1);
  log('crafted gift given to classmate grows saved friendship');
  await page.locator('.ww-2d-map').getByRole('button',{name:'Whispering Wetlands'}).click();
  await equip('Fishing Rod');
  await sleep(300);
  await node('Quiet fishing pool').click();
  await page.getByText(/Line cast!/).waitFor();
  await page.getByText(/A bite! Press F now/).waitFor({timeout:15000});
  await page.keyboard.press('f');
  await page.getByText(/You landed a/).waitFor({timeout:5000});
  assert.equal((await stored(page)).field.inventory.fish,1);
  log('fishing requires cast, real bite window and timely reel');
  await page.keyboard.press('b');
  await page.getByRole('heading',{name:'The Explorer’s Field Guide'}).waitFor();
  assert.equal(await page.locator('.ww-guide-cards article').count(),38);
  assert(Object.keys((await stored(page)).field.album).length>=4);
  assert((await stored(page)).field.bonusAcorns>=3);
  log('persistent 38-slot field guide records unique finds and milestone acorns');
  await page.getByRole('button',{name:'Close activity and return to world'}).click();
  await page.getByRole('button',{name:'Daily adventures'}).click();
  await page.getByRole('heading',{name:"Today's Adventure Board"}).waitFor();
  assert.equal(await page.locator('.ww-daily-quests article').count(),3);
  log('three rotating daily quests display their real counted progress');
  await page.getByRole('button',{name:'Close activity and return to world'}).click();
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('.ww-2d-world').waitFor();
  const persisted=await stored(page);
  assert.equal(persisted.field.inventory.fish,1);
  assert.equal(persisted.field.friends['student:8.1'],1);
  assert.equal(persisted.field.inventory.bugs,1);
  log('inventory, friendships and wildlife persist after reload');
  assert.equal(errors.length,0,JSON.stringify(errors));
  await context.close();

  const threeContext=await browser.newContext({viewport:{width:1440,height:900},deviceScaleFactor:1,reducedMotion:'reduce'});
  const three=await threeContext.newPage(),threeErrors=[];
  three.on('pageerror',e=>threeErrors.push(e.message));
  await three.goto(base,{waitUntil:'domcontentloaded'});
  await three.locator('.ww-world canvas').waitFor({timeout:25000});
  await three.waitForTimeout(850);
  await three.keyboard.press('2');
  assert.equal(await three.getByRole('button',{name:'Equip Butterfly Net (2)'}).getAttribute('aria-pressed'),'true');
  log('PC equipment key 2 actually equips the visible 3D net');
  await three.keyboard.down('Shift');await three.keyboard.down('w');
  await three.waitForTimeout(1050);
  await three.keyboard.up('w');await three.keyboard.up('Shift');
  const stamina=Number(await three.getByRole('progressbar',{name:'Stamina'}).getAttribute('aria-valuenow'));
  assert(stamina<100,'Sprint must spend actual stamina');
  log('camera-relative sprint moves character and consumes stamina');
  await three.keyboard.press('Space');
  await three.getByText('JUMP',{exact:true}).waitFor({timeout:1500});
  log('space triggers physical jump state');
  await three.keyboard.press('Alt');
  await three.getByText('DODGE',{exact:true}).waitFor({timeout:1500});
  log('Alt triggers cooldown-controlled dodge state');
  await three.keyboard.press('1');
  await three.evaluate(()=>window.dispatchEvent(new CustomEvent('wildwood-travel',
   {detail:{x:-9.85,z:-2.15,resourceId:'0:fruit'}})));
  await three.getByText(/\+2 sunberries/).waitFor({timeout:13000});
  assert.equal((await stored(three)).field.inventory.berries,2);
  log('3D click-to-walk reaches harvestable object and collects real resources');
  const sound=three.getByRole('button',{name:'Mute sound'});
  await sound.waitFor({timeout:6000});
  log('first keyboard gesture unlocks the actual Vision sound engine');
  assert.equal(threeErrors.length,0,JSON.stringify(threeErrors));
  await three.screenshot({path:'analysis/academy-gameplay-desktop.png',fullPage:true});
  await threeContext.close();
  console.log(JSON.stringify({success:true,passed},null,2));
 }finally{await browser.close()}
})().catch(e=>{console.error('GAMEPLAY VALIDATION FAILED',e);process.exitCode=1});
