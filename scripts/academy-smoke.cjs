const assert=require('node:assert/strict');
const {chromium}=require('../node_modules/playwright-core');
const fs=require('node:fs');
const base=process.env.SPEAKLAB_BASE||'http://127.0.0.1:5174/ielts-speaking-studio/';
const edge=process.env.BROWSER_EXECUTABLE||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe';
const errors=[],passed=[];
const launchArgs=['--enable-webgl','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--no-sandbox','--use-fake-ui-for-media-stream','--use-fake-device-for-media-stream'];
const sleep=ms=>new Promise(done=>setTimeout(done,ms));
async function click(page,name){await page.getByRole('button',{name,exact:true}).click()}
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:edge,args:launchArgs});
 try{
  const context=await browser.newContext({viewport:{width:1550,height:900},permissions:['microphone'],reducedMotion:'reduce'});
  const page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text())});
  await page.goto(base,{waitUntil:'domcontentloaded'});
  await page.locator('.ww-world canvas').waitFor({timeout:30000});
  await page.waitForTimeout(850);
  const start=await page.locator('.ww-minimap small').innerText();
  await page.keyboard.down('d');await page.waitForTimeout(650);await page.keyboard.up('d');
  const next=await page.locator('.ww-minimap small').innerText();
  assert.notEqual(start,next,'Keyboard movement did not update world position');
  passed.push('real WebGL walking');
  await click(page,'Open village map');
  await page.getByRole('heading',{name:'The Village Atlas'}).waitFor();
  await page.getByRole('button',{name:'Walk to Friendship Orchard'}).click();
  await page.getByRole('heading',{name:'The Village Atlas'}).waitFor({state:'hidden'});
  await page.getByRole('heading',{name:'Friendship Orchard'}).waitFor({timeout:15000});
  passed.push('map walking to another district');
  await click(page,'Open learning storybook');
  await page.getByRole('heading',{name:'My Storybook'}).waitFor();
  assert.equal(await page.locator('.ww-journal-topics button').count(),44);
  await page.locator('.ww-journal-topics button').first().click();
  await page.getByRole('heading',{name:'Today’s class activity'}).waitFor();
  await page.getByRole('button',{name:'Save my story outline'}).waitFor();
  await page.locator('#ww-class-note').fill('My friend likes photography, and we met at university. She helped me stay confident when I changed jobs.');
  await click(page,'Save my story outline');
  await page.getByText('Your outline is preserved.').waitFor();
  passed.push('44 topics accessible and classroom outline persisted');
  await click(page,'Close activity and return to world');
  await click(page,'Open learning storybook');
  await page.locator('.ww-journal-topics button').first().click();
  assert.match(await page.locator('#ww-class-note').inputValue(),/photography/);
  passed.push('classroom saved across reopening');
  await click(page,'Close activity and return to world');
  await page.evaluate(()=>window.dispatchEvent(new CustomEvent('wildwood-travel',{detail:{x:-19.45,z:-13.8,actorId:'student:8.1'}})));
  await page.getByRole('heading',{name:'A friend has a question'}).waitFor({timeout:14000});
  await click(page,'Start our conversation');
  await page.locator('#ww-peer-reply').fill('I think friends make life happier because they offer emotional support. For example, my childhood friend helped me move. Do you agree?');
  await page.getByRole('button',{name:/Share with/}).click();
  await page.getByText('Your conversation is saved in your storybook.').waitFor();
  passed.push('classmate encounter, dialogue branching and saved reply');
  await click(page,'Close activity and return to world');
  await click(page,'Open village map');
  await click(page,'Close activity and return to world');
  await page.evaluate(()=>window.dispatchEvent(new CustomEvent('wildwood-travel',{detail:{x:-5.7,z:0,actorId:'teacher'}})));
  await page.getByRole('heading',{name:'Professor Maple’s classroom'}).waitFor({timeout:16000});
  assert.equal(await page.locator('.ww-mini-quest-grid button').count(),6);
  await page.getByRole('button',{name:/Flower Harvest/}).click();
  await page.getByRole('heading',{name:'Flower Harvest'}).waitFor();
  const topic=await page.locator('.ww-activity-banner').innerText();
  await page.locator('.ww-answer-list button').first().waitFor();
  passed.push('teacher routes to in-world language mini-games');
  const data=await page.evaluate(()=>({topics:window.SPEAKLAB_CONTENT.topics.length,lessons:window.SPEAKLAB_CONTENT.lessons.length}));
  assert.deepEqual(data,{topics:44,lessons:11});
  await page.screenshot({path:'analysis/academy-game-quest.png',fullPage:true});
  await page.reload({waitUntil:'domcontentloaded'});
  await page.locator('.ww-world canvas').waitFor({timeout:30000});
  await click(page,'Open learning storybook');
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('speaklab-progress-v1')));
  assert.match(saved.topicNotes['8.1.study'],/photography/);
  assert.match(saved.topicNotes['8.1.peer'],/childhood friend/);
  passed.push('reload persists classroom and classmate dialogue');
  assert.equal(errors.length,0,'Browser page errors: '+JSON.stringify(errors));
  console.log(JSON.stringify({success:true,passed,topic,data,errors},null,2));
 }finally{await browser.close()}
})().catch(e=>{console.error('INTEGRATION TEST FAILED',e);process.exitCode=1});
